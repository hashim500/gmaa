// Helper to get slice of questions
export function getQuestionsFromBank(count: number = 10): QuizQuestion[] {
  const safeCount = Math.min(Math.max(count, 1), 50);
  return ACCOUNTING_QUESTION_BANK.slice(0, safeCount).map((q, idx) => ({
    ...q,
    id: `q-${idx + 1}`,
  }));
}
